// Import some required functions
const {
    responsesHelpers,
    translationHelpers,
} = require("../../helpers");

const { getResponseObject, handleResponse } = responsesHelpers;

const { getSuitableTranslations } = translationHelpers;

// Import functions for overview management
const overviewOperationsManagmentFunctions = require("../../repositories/overview");

async function getStatistics(req, res) {
    try {
        const result = await overviewOperationsManagmentFunctions.getStatistics(req.data._id, req.query.language);
        handleResponse(result, res);
    }
    catch (err) {
        res.status(500).json(getResponseObject(getSuitableTranslations("Internal Server Error !!", req.query.language), true, {}));
    }
}

module.exports = {
    getStatistics
}